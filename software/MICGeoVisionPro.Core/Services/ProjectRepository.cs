using Microsoft.Data.Sqlite;
using MICGeoVisionPro.Core.Models;

namespace MICGeoVisionPro.Core.Services;

public class ProjectRepository
{
    private readonly string _databasePath;

    public ProjectRepository(string databasePath)
    {
        _databasePath = databasePath;
        EnsureDatabase();
    }

    public static bool IsProjectDatabase(string databasePath)
    {
        try
        {
            using var connection = new SqliteConnection($"Data Source={databasePath};Mode=ReadOnly");
            connection.Open();

            using var command = connection.CreateCommand();
            command.CommandText = "SELECT COUNT(*) FROM projects;";
            command.ExecuteScalar();
            return true;
        }
        catch
        {
            return false;
        }
    }

    public void SaveProject(Project project)
    {
        var payload = ProjectDocument.Serialize(project);

        using var connection = new SqliteConnection($"Data Source={_databasePath}");
        connection.Open();

        using var command = connection.CreateCommand();
        command.CommandText = @"
            CREATE TABLE IF NOT EXISTS projects (
                id TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                description TEXT,
                created_at TEXT NOT NULL,
                payload TEXT NOT NULL
            );
        ";
        command.ExecuteNonQuery();

        command.CommandText = @"
            INSERT INTO projects (id, name, description, created_at, payload)
            VALUES (@id, @name, @description, @createdAt, @payload)
            ON CONFLICT(id) DO UPDATE SET
                name = excluded.name,
                description = excluded.description,
                created_at = excluded.created_at,
                payload = excluded.payload;
        ";

        command.Parameters.AddWithValue("@id", project.Id.ToString());
        command.Parameters.AddWithValue("@name", project.Name);
        command.Parameters.AddWithValue("@description", (object?)project.Description ?? DBNull.Value);
        command.Parameters.AddWithValue("@createdAt", project.CreatedAt.ToString("O"));
        command.Parameters.AddWithValue("@payload", payload);
        command.ExecuteNonQuery();
    }

    public Project LoadProject(Guid projectId)
    {
        using var connection = new SqliteConnection($"Data Source={_databasePath}");
        connection.Open();

        using var command = connection.CreateCommand();
        command.CommandText = "SELECT payload FROM projects WHERE id = @id LIMIT 1;";
        command.Parameters.AddWithValue("@id", projectId.ToString());

        var result = command.ExecuteScalar();
        if (result is null)
        {
            return new Project { Name = "MIC GIS Demo" };
        }

        var payload = result.ToString();
        if (string.IsNullOrWhiteSpace(payload))
        {
            return new Project { Name = "MIC GIS Demo" };
        }

        return ProjectDocument.Deserialize(payload)
            ?? new Project { Name = "MIC GIS Demo" };
    }

    public void ReplaceAll(Project project)
    {
        using (var connection = new SqliteConnection($"Data Source={_databasePath}"))
        {
            connection.Open();

            using var command = connection.CreateCommand();
            command.CommandText = "DELETE FROM projects;";
            command.ExecuteNonQuery();
        }

        SaveProject(project);
    }

    public Project LoadOrCreateDefault()
    {
        var project = new Project
        {
            Name = "MIC GIS Demo",
            Description = "Default project generated by the desktop shell.",
            CreatedAt = DateTime.UtcNow
        };

        using var connection = new SqliteConnection($"Data Source={_databasePath}");
        connection.Open();

        using var command = connection.CreateCommand();
        command.CommandText = "SELECT COUNT(*) FROM projects;";
        var count = Convert.ToInt32(command.ExecuteScalar());

        if (count <= 0)
        {
            var borehole = new Borehole
            {
                Name = "B-01",
                X = 500,
                Y = 600,
                Elevation = 120.5,
                TotalDepth = 76
            };

            borehole.Logs.Add(new Log
            {
                Name = "Lithology Log",
                Type = LogType.Lithology,
                Points =
                [
                    new LogPoint { Depth = 0, Label = "Topsoil", Value = 12 },
                    new LogPoint { Depth = 12, Label = "Clay", Value = 16 },
                    new LogPoint { Depth = 28, Label = "Sand", Value = 17 },
                    new LogPoint { Depth = 45, Label = "Limestone", Value = 31 }
                ]
            });

            project.Boreholes.Add(borehole);
            SaveProject(project);
        }
        else
        {
            var first = connection.CreateCommand();
            first.CommandText = "SELECT payload FROM projects ORDER BY created_at LIMIT 1;";
            var firstResult = first.ExecuteScalar();
            if (firstResult is not null)
            {
                var payload = firstResult.ToString();
                if (!string.IsNullOrWhiteSpace(payload))
                {
                    var loaded = ProjectDocument.Deserialize(payload);
                    if (loaded is not null)
                    {
                        return loaded;
                    }
                }
            }
        }

        return project;
    }

    private void EnsureDatabase()
    {
        var directory = Path.GetDirectoryName(_databasePath);
        if (!string.IsNullOrWhiteSpace(directory))
        {
            Directory.CreateDirectory(directory);
        }

        using var connection = new SqliteConnection($"Data Source={_databasePath}");
        connection.Open();

        using var command = connection.CreateCommand();
        command.CommandText = @"
            CREATE TABLE IF NOT EXISTS projects (
                id TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                description TEXT,
                created_at TEXT NOT NULL,
                payload TEXT NOT NULL
            );
        ";
        command.ExecuteNonQuery();
    }
}
